-- Smart Banking Simulator: initial schema.
-- All money is NUMERIC(19,2); all timestamps are TIMESTAMPTZ and written as UTC instants.

CREATE TABLE app_user (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(50)  NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    role          VARCHAR(20)  NOT NULL,
    enabled       BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uq_app_user_username UNIQUE (username),
    CONSTRAINT ck_app_user_role CHECK (role IN ('CUSTOMER', 'ANALYST'))
);

CREATE TABLE account (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_user_id     BIGINT        NOT NULL REFERENCES app_user (id),
    account_reference VARCHAR(34)   NOT NULL,
    display_name      VARCHAR(80)   NOT NULL,
    currency          VARCHAR(3)    NOT NULL,
    balance           NUMERIC(19,2) NOT NULL,
    status            VARCHAR(20)   NOT NULL,
    version           BIGINT        NOT NULL DEFAULT 0,
    created_at        TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT uq_account_reference UNIQUE (account_reference),
    CONSTRAINT ck_account_currency CHECK (currency IN ('EUR', 'PLN', 'USD')),
    CONSTRAINT ck_account_balance_non_negative CHECK (balance >= 0),
    CONSTRAINT ck_account_status CHECK (status IN ('ACTIVE', 'FROZEN', 'CLOSED'))
);

CREATE INDEX ix_account_owner ON account (owner_user_id);

CREATE TABLE transfer (
    id                     UUID          PRIMARY KEY,
    source_account_id      BIGINT        NOT NULL REFERENCES account (id),
    destination_account_id BIGINT        NOT NULL REFERENCES account (id),
    amount                 NUMERIC(19,2) NOT NULL,
    currency               VARCHAR(3)    NOT NULL,
    status                 VARCHAR(20)   NOT NULL,
    rejection_reason       VARCHAR(40),
    reference              VARCHAR(140),
    idempotency_key        VARCHAR(80),
    request_fingerprint    VARCHAR(64),
    initiated_by_user_id   BIGINT        NOT NULL REFERENCES app_user (id),
    created_at             TIMESTAMPTZ   NOT NULL,
    completed_at           TIMESTAMPTZ,
    CONSTRAINT ck_transfer_amount_positive CHECK (amount > 0),
    CONSTRAINT ck_transfer_distinct_accounts CHECK (source_account_id <> destination_account_id),
    CONSTRAINT ck_transfer_status CHECK (status IN ('PENDING', 'COMPLETED', 'REJECTED')),
    CONSTRAINT ck_transfer_rejection_reason CHECK ((status = 'REJECTED') = (rejection_reason IS NOT NULL)),
    CONSTRAINT ck_transfer_completed_at CHECK ((status = 'COMPLETED') = (completed_at IS NOT NULL)),
    -- A client retry with the same key from the same user maps to the same transfer.
    CONSTRAINT uq_transfer_idempotency UNIQUE (initiated_by_user_id, idempotency_key)
);

CREATE INDEX ix_transfer_source_created ON transfer (source_account_id, created_at DESC);
CREATE INDEX ix_transfer_destination_created ON transfer (destination_account_id, created_at DESC);

CREATE TABLE ledger_entry (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transfer_id UUID          REFERENCES transfer (id),
    account_id  BIGINT        NOT NULL REFERENCES account (id),
    amount      NUMERIC(19,2) NOT NULL,
    entry_type  VARCHAR(20)   NOT NULL,
    created_at  TIMESTAMPTZ   NOT NULL,
    CONSTRAINT ck_ledger_entry_type CHECK (entry_type IN ('DEBIT', 'CREDIT', 'OPENING_BALANCE')),
    -- Debits are stored as negative amounts, credits and opening balances as positive ones,
    -- so a completed transfer's entries sum to zero and an account's entries sum to its balance.
    CONSTRAINT ck_ledger_entry_sign CHECK (
        (entry_type = 'DEBIT' AND amount < 0) OR
        (entry_type IN ('CREDIT', 'OPENING_BALANCE') AND amount > 0)),
    CONSTRAINT ck_ledger_entry_transfer CHECK ((entry_type = 'OPENING_BALANCE') = (transfer_id IS NULL))
);

CREATE INDEX ix_ledger_entry_account ON ledger_entry (account_id, created_at DESC);
CREATE INDEX ix_ledger_entry_transfer ON ledger_entry (transfer_id);

-- Completed ledger entries are immutable: corrections must be new, reversing entries.
CREATE FUNCTION forbid_ledger_mutation() RETURNS trigger AS $$
BEGIN
    RAISE EXCEPTION 'ledger_entry rows are immutable; post a reversing entry instead';
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_ledger_entry_immutable
    BEFORE UPDATE OR DELETE ON ledger_entry
    FOR EACH ROW EXECUTE FUNCTION forbid_ledger_mutation();

CREATE TABLE fraud_alert (
    id                  UUID         PRIMARY KEY,
    transfer_id         UUID         NOT NULL REFERENCES transfer (id),
    rule_code           VARCHAR(40)  NOT NULL,
    explanation         VARCHAR(500) NOT NULL,
    severity            VARCHAR(10)  NOT NULL,
    review_status       VARCHAR(20)  NOT NULL,
    review_note         VARCHAR(500),
    reviewed_by_user_id BIGINT       REFERENCES app_user (id),
    reviewed_at         TIMESTAMPTZ,
    created_at          TIMESTAMPTZ  NOT NULL,
    CONSTRAINT ck_fraud_alert_severity CHECK (severity IN ('LOW', 'MEDIUM', 'HIGH')),
    CONSTRAINT ck_fraud_alert_review_status CHECK (review_status IN ('OPEN', 'CONFIRMED', 'DISMISSED')),
    CONSTRAINT uq_fraud_alert_transfer_rule UNIQUE (transfer_id, rule_code)
);

CREATE INDEX ix_fraud_alert_status_created ON fraud_alert (review_status, created_at DESC);
CREATE INDEX ix_fraud_alert_rule ON fraud_alert (rule_code);

CREATE TABLE audit_event (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_user_id    BIGINT       REFERENCES app_user (id),
    event_type       VARCHAR(50)  NOT NULL,
    entity_reference VARCHAR(100),
    created_at       TIMESTAMPTZ  NOT NULL
);

CREATE INDEX ix_audit_event_created ON audit_event (created_at DESC);
